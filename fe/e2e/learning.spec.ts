test('sách từ vựng hiển thị nội dung và nhớ trang, mục đang đọc', async ({ page }) => {
  const nextPageUrl = /\/api\/catalog\/book\/VOCABULARY\?level=N5&page=2&limit=8$/
  let nextPageRequests = 0
  await page.route(nextPageUrl, route => {
    nextPageRequests++
    return route.continue()
  })
  const nextPage = page.waitForResponse(response => nextPageUrl.test(response.url()) && response.ok())
  await page.goto('/tu-vung?level=N5')
  const first = page.locator('.book-entry').first()
  await expect(first.getByRole('heading', { name: /学生/ })).toBeVisible()
  await expect(first.locator('h2 rt')).toHaveText('がくせい')
  await expect(first.getByText('HỌC SINH', { exact: true })).toBeVisible()
  await expect(first.getByText('học sinh, sinh viên', { exact: true })).toBeVisible()
  await expect(first.getByRole('heading', { name: 'Câu ví dụ' })).toBeVisible()
  await nextPage
  await page.getByRole('button', { name: 'Trang sau' }).first().click()
  await expect(page.getByText(/^Mục 9–16/)).toBeVisible()
  expect(nextPageRequests).toBe(1)
  const saved = page.locator('.book-entry').nth(2)
  await saved.getByRole('button', { name: 'Học đến đây' }).click()
  await expect(saved.getByRole('button', { name: 'Học đến đây' })).toHaveAttribute('aria-pressed', 'true')
  const url = page.url()
  const open = saved.getByRole('button', { name: 'Mở mục' })
  await open.click()
  const popup = page.getByRole('dialog')
  await expect(popup).toBeVisible()
  await expect(page).toHaveURL(url)
  await page.keyboard.press('Escape')
  await expect(popup).toBeHidden()
  await expect(open).toBeFocused()
  await expect(page.getByText(/^Mục 9–16/)).toBeVisible()
  await expect(saved.getByRole('button', { name: 'Học đến đây' })).toHaveAttribute('aria-pressed', 'true')
  await page.goto('/ngu-phap')
  await page.getByRole('navigation', { name: 'Khu vực học tập' }).getByRole('link', { name: 'Từ vựng' }).click()
  await expect(page.getByText(/^Mục 9–16/)).toBeVisible()
  await expect(saved.getByRole('button', { name: 'Học đến đây' })).toHaveAttribute('aria-pressed', 'true')
})

test('đánh dấu và học tiếp đúng vị trí của ba sách sau khi tải lại', async ({ page }) => {
  const books = [
    { name: 'Từ vựng', path: '/tu-vung?level=N5&page=2', index: 2 },
    { name: 'Ngữ pháp', path: '/ngu-phap?level=N5&q=' + encodeURIComponent('đánh dấu chủ đề'), index: 0 },
    { name: 'Kanji', path: '/kanji?level=N5', index: 3 }
  ]
  const marks: string[] = []
  const markButton = { name: 'Học đến đây' }
  for (const { name, path, index } of books) {
    await page.goto(path)
    const row = page.locator('.book-entry').nth(index)
    const mark = row.getByRole('button', markButton)
    await expect(mark).toHaveAttribute('aria-pressed', 'false')
    await mark.click()
    await expect(mark).toHaveAttribute('aria-pressed', 'true')
    marks.push((await row.getByRole('heading', { level: 2 }).getAttribute('id'))!)
    if (name === 'Từ vựng') {
      await page.getByRole('button', { name: 'Trang sau' }).last().click()
      await expect(page.getByText(/^Mục 17–24/)).toBeVisible()
    }
  }

  await page.goto('/')
  await page.reload()
  const resume = page.getByRole('region', { name: 'Học tiếp' })
  await expect(resume.getByRole('link')).toHaveCount(3)
  for (const [index, { name, path }] of books.entries()) {
    await resume.getByRole('link', { name: new RegExp('^' + name) }).click()
    const heading = page.locator('#' + marks[index])
    await expect(heading).toBeFocused()
    await expect(heading).toBeInViewport()
    const saved = new URL(path, 'http://localhost')
    const actual = new URL(page.url())
    expect(actual.pathname).toBe(saved.pathname)
    expect(actual.searchParams.get('level')).toBe(saved.searchParams.get('level'))
    expect(actual.searchParams.get('q')).toBe(saved.searchParams.get('q'))
    expect(actual.searchParams.get('page')).toBe(saved.searchParams.get('page') ?? '1')
    expect(actual.hash).toBe('#' + marks[index])
    if (name === 'Từ vựng') {
      await page.getByRole('link', { name: /^Học tiếp/ }).click()
      await expect(heading).toBeFocused()
      await expect(heading).toBeInViewport()
    } else if (name === 'Kanji') {
      await page.locator('.book-entry').nth(3).getByRole('button', markButton).click()
      await expect(page.getByRole('link', { name: /^Học tiếp/ })).toHaveCount(0)
    }
    await page.getByRole('link', { name: 'Trang chủ', exact: true }).click()
  }
  await expect(resume.getByRole('link')).toHaveCount(2)
})

